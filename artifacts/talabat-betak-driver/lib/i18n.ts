export function directionForLocale(locale: Locale): 'rtl' | 'ltr' {
  return locale === 'ar' ? 'rtl' : 'ltr';
}

export function normalizeLocale(value: unknown): Locale {
  return value === 'en' ? 'en' : DEFAULT_LOCALE;
}

export function translate(
  locale: Locale,
  key: string,
  params: Record<string, string | number> = {},
): string {
  const value = translations[locale][key] ?? translations[DEFAULT_LOCALE][key] ?? key;
  return typeof value === 'function' ? value(params) : value;
}

export function statusLabel(locale: Locale, status: unknown): string {
  if (typeof status !== 'string') return translate(locale, 'common.unknown');
  const key = statusKeys[status] ?? statusKeys[status.toLowerCase()];
  return key ? translate(locale, key) : translate(locale, 'common.unknown');
}

export function documentTypeLabel(locale: Locale, documentType: unknown): string {
  if (typeof documentType !== 'string') return translate(locale, 'common.unknown');
  const key = documentKeys[documentType.toLowerCase()];
  return key ? translate(locale, key) : translate(locale, 'common.unknown');
}

export function formatCurrency(locale: Locale, amount: number | undefined | null): string {
  const value = (amount ?? 0).toFixed(2);
  return locale === 'ar' ? `${value} ${translate(locale, 'common.egyptianPound')}` : `${value} ${translate(locale, 'common.egyptianPound')}`;
}

export function formatDate(locale: Locale, dateString: string): string {
  try {
    const date = new Date(dateString);
    if (Number.isNaN(date.getTime())) return dateString;
    return date.toLocaleDateString(locale === 'ar' ? 'ar-EG' : 'en-EG', {
      month: 'short',
      day: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    });
  } catch {
    return dateString;
  }
}

